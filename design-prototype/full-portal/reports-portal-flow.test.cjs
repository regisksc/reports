const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');

const sourcePath = require.resolve('./dist/reports-portal-flow.js');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(sourcePath, 'utf8'), context, { filename: sourcePath });
const flow = context.ReportsFlow;
const service = { id: 'flooding', name: 'Flooding', group: 'Street Problems/Repairs', mode: 'guest-form', boundary: 'City Boundary', attachmentLimit: 5, attachments: 'required', questionCount: 4, preliminaryCount: 0 };
const escape = (value) => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&#39;');
const copy = (value) => JSON.parse(JSON.stringify(value));

test('Building Permit Inspection continues without photos and never offers or rejects unsupported attachments', () => {
  const row = require('./reports-portal-catalog.json').find((entry) => entry.name === 'Building Permit Inspection');
  assert.ok(row);
  const selected = { ...service, id: 'building-permit-inspection', name: row.name, attachments: 'none', attachmentLimit: null };
  const draft = { ...flow.create(selected), step: 'photos' };
  const markup = flow.render(draft, selected, escape);
  assert.doesNotMatch(markup, /data-action="flow-add-photo"/);
  assert.match(markup, /No photos are needed/);
  assert.equal(flow.handle(draft, selected, 'add-photo'), draft);
  const continued = flow.handle(draft, selected, 'next');
  assert.equal(continued.step, 'contact');
  assert.equal(continued.error, '');
  const unlimited = { ...selected, attachments: 'optional' };
  assert.equal(flow.handle(draft, unlimited, 'add-photo').photos.length, 1);
});

test('a new local report uses friendly example questions and service photo guidance', () => {
  const draft = flow.create(service);
  assert.equal(draft.serviceId, 'flooding');
  assert.equal(draft.step, 'details');
  assert.equal(draft.answers.description, '');
  assert.equal(draft.confirmation, false);
  const markup = flow.render(draft, service, escape);
  assert.match(markup, /Flooding/);
  assert.match(markup, /Where is water collecting/);
  assert.match(markup, /Example questions/);
  assert.doesNotMatch(markup, /configuration entries/);
  const photos = flow.render({ ...draft, step: 'photos' }, service, escape);
  assert.match(photos, /Photos are required for this service/);
  assert.doesNotMatch(photos, /recorded City configuration/);
  assert.match(markup, /data-flow-field="description"/);
  assert.match(markup, /data-action="flow-next"/);
  assert.match(markup, /data-action="flow-save"/);
});

test('a local report reaches a demo receipt only after required details, location, evidence, contact and review consent', () => {
  const edit = (draft, field, value) => flow.handle(draft, service, 'field', { field, value });
  const advance = (draft, selected = service) => flow.handle(draft, selected, 'next');
  const markup = (draft, selected = service) => flow.render(draft, selected, escape);
  const untouched = flow.create(service);
  let draft = advance(untouched);
  assert.equal(draft.step, 'details');
  assert.match(draft.error, /Describe/);
  assert.match(markup(draft), /role="alert"/);
  draft = edit(draft, 'description', '<water>');
  assert.equal(untouched.answers.description, '');
  assert.match(markup(draft), /&lt;water&gt;/);
  draft = edit(draft, 'extra', true);
  assert.match(markup(draft), /data-flow-field="extraDetail"/);
  assert.match(advance(draft).error, /extra detail/);
  draft = edit(draft, 'extraDetail', 'Across the curb');
  draft = advance(draft);
  assert.equal(draft.step, 'location');
  assert.match(markup(draft), /data-flow-field="address"/);
  assert.match(markup(draft), /flow-confirm/);
  assert.match(advance(draft).error, /address/);
  draft = edit(draft, 'address', '200 N Spring St, Los Angeles');
  assert.match(advance(draft).error, /Confirm/);
  draft = flow.handle(draft, service, 'confirm');
  assert.equal(draft.answers.locationConfirmed, true);
  draft = edit(draft, 'address', '201 N Spring St, Los Angeles');
  assert.equal(draft.answers.locationConfirmed, false);
  draft = flow.handle(draft, service, 'confirm');
  assert.match(markup(draft), /Location confirmed/);
  draft = advance(draft);
  assert.equal(draft.step, 'photos');
  assert.match(markup(draft), /Sample evidence/);
  assert.match(advance(draft).error, /photo/);
  draft = flow.handle(draft, service, 'add-photo');
  assert.equal(draft.photos.length, 1);
  assert.equal(flow.handle({ ...draft, answers: { ...draft.answers, reviewConsent: true } }, service, 'add-photo').answers.reviewConsent, false);
  assert.equal(flow.handle({ ...draft, answers: { ...draft.answers, reviewConsent: true } }, service, 'remove-photo', { index: 0 }).answers.reviewConsent, false);
  assert.match(markup(draft), /flow-remove-photo/);
  const limited = { ...service, attachmentLimit: 1 };
  assert.match(flow.handle(draft, limited, 'add-photo').error, /limit/);
  draft = flow.handle(draft, service, 'remove-photo', { index: 0 });
  assert.equal(draft.photos.length, 0);
  draft = flow.handle(draft, service, 'add-photo');
  draft = advance(draft);
  assert.equal(draft.step, 'contact');
  assert.match(markup(draft), /data-flow-field="contactMode"/);
  assert.match(advance(draft).error, /Choose/);
  draft = edit(draft, 'contactMode', 'named');
  assert.match(markup(draft), /data-flow-field="email"/);
  assert.match(advance(draft).error, /name/);
  draft = edit(draft, 'name', 'Demo Resident');
  draft = edit(draft, 'email', 'invalid');
  assert.match(advance(draft).error, /email/);
  draft = edit(draft, 'email', 'demo@example.com');
  draft = advance(draft);
  assert.equal(draft.step, 'review');
  assert.match(markup(draft), /&lt;water&gt;/);
  assert.match(markup(draft), /data-flow-field="reviewConsent"/);
  assert.match(flow.handle(draft, service, 'submit').error, /confirm/);
  assert.equal(advance(draft).step, 'review');
  draft = edit(draft, 'reviewConsent', true);
  assert.match(markup(draft), /data-flow-field="reviewConsent" checked/);
  draft = flow.handle(draft, service, 'submit');
  assert.equal(draft.step, 'confirmation');
  assert.equal(draft.confirmation, true);
  assert.match(markup(draft), /Demo receipt/);
  assert.match(markup(draft), /No request was sent to the City/);
  assert.equal(flow.handle(draft, service, 'submit'), draft);
  assert.equal(advance(draft), draft);
  assert.equal(flow.handle(draft, service, 'save').saved, true);
  assert.equal(flow.handle(draft, service, 'back').step, 'review');
  assert.equal(flow.handle(untouched, service, 'back'), untouched);
  assert.equal(flow.handle(draft, service, 'unknown'), draft);
  assert.equal(flow.handle(draft, service, 'field', { field: '__proto__', value: {} }), draft);
  assert.equal(flow.handle(untouched, service, 'confirm').answers.locationConfirmed, false);
  const optional = { ...service, name: 'Graffiti Removal', attachments: 'optional' };
  assert.match(markup(untouched, optional), /What needs attention/);
  let anonymous = { ...flow.create(optional), step: 'photos' };
  assert.match(markup(anonymous, optional), /Evidence is optional/);
  anonymous = advance(anonymous, optional);
  anonymous = edit(anonymous, 'contactMode', 'anonymous');
  assert.match(markup(anonymous, optional), /No contact details/);
  assert.equal(advance(anonymous, optional).step, 'review');
  const namedRequired = { ...optional, mode: 'contact-required' };
  assert.match(advance(anonymous, namedRequired).error, /contact details/);
  assert.doesNotMatch(markup(anonymous, namedRequired), /value="anonymous"/);
  assert.match(markup({ ...draft, step: 'review', photos: [], answers: { ...draft.answers, contactMode: 'anonymous' } }, optional), /No contact details/);
  const back = flow.handle({ ...draft, step: 'location' }, service, 'back');
  assert.equal(back.step, 'details');
  assert.equal(copy(untouched).answers.description, '');
});
